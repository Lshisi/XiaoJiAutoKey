#pragma once

#ifdef _KERNEL_MODE
#include <wdm.h>
#else
#include <Windows.h>
#include <winioctl.h>
#endif

#include <guiddef.h>

// {19A81717-2670-4384-9D5E-7E9E6345597E}
DEFINE_GUID(GUID_DEVINTERFACE_XIAOJI_VHID,
    0x19a81717, 0x2670, 0x4384, 0x9d, 0x5e, 0x7e, 0x9e, 0x63, 0x45, 0x59, 0x7e);

#define XIAOJI_VHID_HARDWARE_ID L"Root\\XiaoJiVhid"
#define XIAOJI_VHID_SERVICE_NAME L"XiaoJiVhid"
#define XIAOJI_VHID_INF_NAME L"XiaoJiVhid.inf"
#define XIAOJI_VHID_PROTOCOL_VERSION 0x00010000UL
#define XIAOJI_VHID_DRIVER_VERSION 0x00010000UL

#define IOCTL_XIAOJI_VHID_ACQUIRE \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x800, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
#define IOCTL_XIAOJI_VHID_RELEASE \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x801, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
#define IOCTL_XIAOJI_VHID_HEARTBEAT \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x802, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
#define IOCTL_XIAOJI_VHID_KEYBOARD \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x803, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
#define IOCTL_XIAOJI_VHID_MOUSE_BUTTON \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x804, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
#define IOCTL_XIAOJI_VHID_MOUSE_MOVE \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x805, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
#define IOCTL_XIAOJI_VHID_CONSUMER \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x806, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
#define IOCTL_XIAOJI_VHID_RELEASE_ALL \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x807, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
#define IOCTL_XIAOJI_VHID_GET_STATUS \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x808, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)

#pragma pack(push, 1)

typedef struct XIAOJI_VHID_HEADER {
    ULONG Size;
    ULONG Version;
} XIAOJI_VHID_HEADER;

typedef struct XIAOJI_VHID_KEYBOARD_INPUT {
    XIAOJI_VHID_HEADER Header;
    USHORT Usage;
    UCHAR Pressed;
    UCHAR Reserved;
} XIAOJI_VHID_KEYBOARD_INPUT;

typedef struct XIAOJI_VHID_MOUSE_BUTTON_INPUT {
    XIAOJI_VHID_HEADER Header;
    UCHAR Button;
    UCHAR Pressed;
    USHORT Reserved;
} XIAOJI_VHID_MOUSE_BUTTON_INPUT;

typedef struct XIAOJI_VHID_MOUSE_MOVE_INPUT {
    XIAOJI_VHID_HEADER Header;
    SHORT X;
    SHORT Y;
    SHORT Wheel;
    SHORT Pan;
} XIAOJI_VHID_MOUSE_MOVE_INPUT;

typedef struct XIAOJI_VHID_CONSUMER_INPUT {
    XIAOJI_VHID_HEADER Header;
    USHORT Usage;
    UCHAR Pressed;
    UCHAR Reserved;
} XIAOJI_VHID_CONSUMER_INPUT;

typedef struct XIAOJI_VHID_STATUS {
    ULONG Size;
    ULONG ProtocolVersion;
    ULONG DriverVersion;
    ULONG Flags;
    ULONG ActiveKeyboardUsages;
    ULONG ActiveMouseButtons;
    ULONG WatchdogTimeoutMs;
} XIAOJI_VHID_STATUS;

#pragma pack(pop)

#define XIAOJI_VHID_STATUS_ACQUIRED 0x00000001UL
#define XIAOJI_VHID_STATUS_STARTED 0x00000002UL
#define XIAOJI_VHID_WATCHDOG_TIMEOUT_MS 2500UL

